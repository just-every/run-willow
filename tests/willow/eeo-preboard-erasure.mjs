import assert from 'node:assert/strict'
import { confirmPreboardBrowser } from './eeo-invitations-browser.mjs'
export async function preboardErasure(h,owner,staff,packet,expired,portal) {
 const api=(path,body,status)=>h.api(path,owner,body,status)
 const hr=(path,body,status)=>h.api(path,staff.hr.cookie,body,status)
 const day=offset=>new Date(Date.now()+offset*86400000).toISOString().slice(0,10)
 await hr('erasure.request',{preboarding:packet.id,source:'own_request',receivedOn:day(0)})
 await h.api(`erasure/preview?preboarding=${packet.id}`,staff.hr.cookie,undefined,403)
 const hold=await api('hold.place',{scope:'person',ref:packet.id,reason:'Review evidence',reviewDate:day(30)})
 const preview=await api(`erasure/preview?preboarding=${packet.id}`)
 assert.equal(preview.confirmable,true,JSON.stringify(preview.blockers))
 assert.equal(preview.items.find(row=>row.id==='preboard_eeo').disposition,'held')
 assert.equal(preview.copies.providers.length,1)
 const receiptId=await confirmPreboardBrowser(h,owner,packet.id)
 const result=receiptId ? {receipt:receiptId} : await api('erasure.confirm',{preboarding:packet.id,digest:preview.digest})
 const receipt=await api(`erasure/receipts/${result.receipt}`)
 assert.ok(!JSON.stringify(receipt).includes('Dara Decliner'))
 assert.equal(receipt.counts.find(row=>row.store==='preboard_eeo').rows,1)
 assert.ok(receipt.providerRequests.some(row=>row.open))
 const provider=receipt.providerRequests[0]
 await api('erasure.provider',{request:provider.id,outcome:'failed',evidence:'Provider has not confirmed deletion'})
 assert.equal((await api(`erasure/receipts/${result.receipt}`)).providerRequests[0].open,true)
 await portal(packet.link,undefined,404)
 await hr(`eeo/preboarding/${packet.id}`,undefined,404)
 assert.ok(!(await hr('preboarding')).some(row=>row.id===packet.id))
 const retained=await api('retained')
 assert.ok(retained.records.some(row=>row.table==='wl_preboard_eeo_answers'&&row.values===null))
 assert.ok(!JSON.stringify(retained).includes('token_hash'))
 await api('eeo.grant',{member:(await api('me')).id,enabled:true})
 const exact=await api('retained')
 const answer=exact.records.find(row=>row.table==='wl_preboard_eeo_answers')
 assert.equal(answer.values.hispanic,'declined')
 assert.equal(answer.hold,hold.id)
 await api('eeo.grant',{member:(await api('me')).id,enabled:false})
 await api('hold.release',{hold:hold.id})
 // An unanswered expired packet also has a complete owner-reviewed erasure door.
 await hr('erasure.request',{preboarding:expired.id,source:'retention_expiry',receivedOn:day(0)})
 const expiredPreview=await api(`erasure/preview?preboarding=${expired.id}`)
 assert.equal(expiredPreview.confirmable,true)
 await api('erasure.confirm',{preboarding:expired.id,digest:expiredPreview.digest})
 assert.ok(!(await hr('preboarding')).some(row=>row.id===expired.id))
}
