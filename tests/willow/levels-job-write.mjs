// ROLE-004: exact native edits and the typed job approval chain through HTTP.
import assert from 'node:assert/strict'
import { day } from './regression-fixture.mjs'
import { publishTemplate } from './publish-template.mjs'

export async function jobWriteProof(h, owner, fx) {
 const { api, join, schedule } = fx
 const apply = async plan => api('level.apply', { review: (await api('level.preview', plan)).id })
 const member = async number => {
  const key = `synthetic-willow-${number}`, person = await join(key)
  const access = await api('access.give', { person: person.person })
  return { ...person, member: access.id, cookie: await h.signIn(`${key}@example.com`, { requested: true }) }
 }
 const editor = await member(401), requester = await member(402)
 const target = await join('synthetic-willow-403'), pending = await join('synthetic-willow-404')
 const outside = await join('synthetic-willow-405')
 const department = await api('department.create', { name: 'synthetic-willow-406' })
 const location = await api('location.create', { name: 'synthetic-willow-407', timezone:'UTC' })
 const secondSchedule = await api('schedule.create', { name: 'synthetic-willow-408', mon: '4', tue: '4', wed: '4', thu: '4', fri: '4' })
 const fields = ['jobTitle', 'departmentId', 'locationId', 'managerPersonId', 'scheduleId', 'employmentType', 'employmentStatus', 'fte', 'startDate', 'endDate']
 const rules = mode => ({ self: {}, others: Object.fromEntries(fields.map(field => [field, mode])) })
 const editLevel = await apply({ kind: 'level', name: 'synthetic-willow-409', permissions: [], jobFields: rules('edit') })
 const approvalLevel = await apply({ kind: 'level', name: 'synthetic-willow-410', permissions: [], jobFields: rules('approval') })
 await apply({ kind: 'assignment', member: editor.member, levels: [editLevel.id] })
 await apply({ kind: 'assignment', member: requester.member, levels: [approvalLevel.id] })
 const as = (who, path, body, status) => h.api(path, who.cookie, body, status)
 const profile = (person, date) => api(`people/${person}${date ? `?asOf=${date}` : ''}`)
 const period = async (person, id) => (await profile(person)).employment.find(row => row.id === id)
 const edit = async (field, value, effectiveFrom, periodId = target.period, status) => as(editor, 'job.field', {
  person: target.person, period: periodId, revision: (await period(target.person, periodId)).revision,
  field, value, effectiveFrom, reason: 'synthetic-willow-411',
 }, status)
 const original = await period(target.person, target.period), firstPay = original.terms[0].pay
 const first = await edit('jobTitle', 'synthetic-willow-412', day(10))
 await as(editor, 'job.field', { person: target.person, period: target.period, revision: original.revision, field: 'jobTitle', value: 'synthetic-willow-413', effectiveFrom: day(11), reason: 'synthetic-willow-411' }, 409)
 await edit('departmentId', department.id, day(11))
 await edit('locationId', location.id, day(12))
 await edit('managerPersonId', editor.person, day(13))
 await edit('scheduleId', secondSchedule.id, day(14))
 await edit('fte', '0.6', day(15))
 await edit('startDate', day(-110), day(16))
 const type = await edit('employmentType', 'part_time', day(20))
 await edit('endDate', day(300), day(21), type.period)
 const result = await period(target.person, type.period), term = result.terms.find(row => row.id === type.terms)
 assert.equal(result.employmentType, 'part_time')
 assert.equal(result.startDate, day(20))
 assert.equal(result.endDate, day(300))
 assert.equal((await period(target.person, target.period)).startDate, day(-110))
 assert.equal(term.jobTitle, 'synthetic-willow-412')
 assert.equal(term.department.id, department.id)
 assert.equal(term.location.id, location.id)
 assert.equal(term.manager.id, editor.person)
 assert.equal(term.schedule.id, secondSchedule.id)
 assert.equal(term.fte, 0.6)
 assert.deepEqual(term.pay, firstPay, 'Exact job rights carry pay without granting pay authority')
 assert.ok((await period(target.person, target.period)).terms.some(row => row.id === first.terms), 'Earlier versions remain immutable history')
 assert.equal((await profile(target.person, day(9))).current.jobTitle, 'Present role')
 assert.equal((await profile(target.person, day(10))).current.jobTitle, 'synthetic-willow-412')
 await as(editor, 'job.field', { person: editor.person, period: editor.period, revision: (await period(editor.person, editor.period)).revision, field: 'jobTitle', value: 'synthetic-willow-414', effectiveFrom: day(30), reason: 'synthetic-willow-411' }, 403)
 await as(editor, 'job.field', { person: outside.person, revision: (await period(outside.person, outside.period)).revision, field: 'managerPersonId', value: outside.person, effectiveFrom: day(30), reason: 'synthetic-willow-411' }, 409)
 await as(editor, 'job.field', { person: outside.person, revision: (await period(outside.person, outside.period)).revision, field: 'jobTitle', value: 'synthetic-willow-414', effectiveFrom: day(30), reason: 'synthetic-willow-411', payBasis: 'salary', payAmount: '1' }, 400)
 await as(editor, 'mover.schedule', { period: outside.period, effectiveFrom: day(30), reason: 'synthetic-willow-411', jobTitle: 'synthetic-willow-414' }, 403)

 const statusPerson = await join('synthetic-willow-422')
 const setStatus = async (value, effectiveFrom, status) => as(editor, 'job.field', { person: statusPerson.person, period: statusPerson.period, revision: (await period(statusPerson.person, statusPerson.period)).revision, field: 'employmentStatus', value, effectiveFrom, reason: 'synthetic-willow-423' }, status)
 await setStatus('former', day(70))
 assert.equal((await period(statusPerson.person, statusPerson.period)).endDate, day(70))
 await setStatus('active', day(71))
 assert.equal((await period(statusPerson.person, statusPerson.period)).endDate, null)
 await setStatus('upcoming', day(80))
 assert.equal((await profile(statusPerson.person)).status, 'upcoming')
 await setStatus('active', day(-90))
 assert.equal((await profile(statusPerson.person)).status, 'active')
 await setStatus('former', day(-1))
 await setStatus('active', day(1), 409)
 assert.equal((await profile(statusPerson.person)).status, 'former', 'Ended employment requires the native rehire flow')

 const mover = await publishTemplate(h, owner, { name: 'synthetic-willow-415', kind: 'mover', taskTitle: ['synthetic-willow-416'], taskAssignee: ['hr'], taskDueDays: ['0'] })
 await api('change.chain', { requestType: 'job', template: mover.id, stepRole: ['hr'] })
 const plan = { person: pending.person, effectiveFrom: day(40), reason: 'synthetic-willow-417', jobTitle: 'synthetic-willow-418', departmentId: department.id, locationId: location.id, managerPersonId: editor.person, scheduleId: secondSchedule.id, employmentType: 'part_time', fte: '0.4', startDate: day(-120), endDate: day(250) }
 await as(requester, 'job.field', { person: pending.person, revision: (await period(pending.person, pending.period)).revision, field: 'jobTitle', value: 'synthetic-willow-418', effectiveFrom: day(40), reason: 'synthetic-willow-417' }, 403)
 await as(requester, 'change.request', { ...plan, payIncreasePercent: '1' }, 403)
 await as(requester, 'change.request', { ...plan, person: requester.person }, 403)
 const proposed = await as(requester, 'change.request', plan)
 assert.equal(proposed.type, 'job')
 assert.equal((await profile(pending.person, day(40))).current.jobTitle, 'Present role', 'A proposal does not publish terms')
 const detail = await api(`change-requests/${proposed.id}`)
 await as(requester, 'change.decide', { request: proposed.id, state: detail.state, decision: 'approve' }, 403)
 const approved = await api('change.decide', { request: proposed.id, state: detail.state, decision: 'approve' })
 assert.equal(approved.status, 'approved')
 const published = await period(pending.person, approved.result.period), approvedTerm = published.terms.find(row => row.id === approved.result.terms)
 assert.equal(approvedTerm.fte, 0.4)
 assert.equal(approvedTerm.jobTitle, plan.jobTitle)
 assert.equal(approvedTerm.department.id, department.id)
 assert.equal(approvedTerm.location.id, location.id)
 assert.equal(approvedTerm.manager.id, editor.person)
 assert.equal(approvedTerm.schedule.id, secondSchedule.id)
 assert.equal(published.employmentType, 'part_time')
 assert.equal(published.endDate, plan.endDate)
 assert.equal((await period(pending.person, pending.period)).startDate, plan.startDate)
 assert.ok(approved.result.case, 'Typed approval starts the configured native mover workflow')
 assert.deepEqual((await as(requester, 'me')).permissions, [], 'Fine approval never supplies a broad or pay permission')

 const statusRequest = await as(requester, 'change.request', { person: outside.person, effectiveFrom: day(75), reason: 'synthetic-willow-424', employmentStatus: 'former' })
 const statusView = await api(`change-requests/${statusRequest.id}`)
 await api('change.decide', { request: statusRequest.id, state: statusView.state, decision: 'approve' })
 assert.equal((await period(outside.person, outside.period)).endDate, day(75), 'Approved employment status derives native period dates')

 // A request stays pending when its current requester loses the named right or its scope.
 const title = await apply({ kind: 'level', name: 'synthetic-willow-419', permissions: [], jobFields: { self: {}, others: { jobTitle: 'approval' } } })
 await apply({ kind: 'assignment', member: requester.member, levels: [title.id] })
 const bounded = await as(requester, 'change.request', { person: outside.person, effectiveFrom: day(60), reason: 'synthetic-willow-420', jobTitle: 'synthetic-willow-421' })
 const state = (await api(`change-requests/${bounded.id}`)).state
 await as(requester, 'change.edit', { request: bounded.id, state, person: outside.person, effectiveFrom: day(60), reason: 'synthetic-willow-420', jobTitle: 'synthetic-willow-421', locationId: location.id }, 403)
 await apply({ kind: 'assignment', member: requester.member, levels: [] })
 await api('change.decide', { request: bounded.id, state, decision: 'approve' }, 403)
 assert.equal((await api(`change-requests/${bounded.id}`)).status, 'pending')
 await apply({ kind: 'assignment', member: requester.member, levels: [title.id] })
 await apply({ kind: 'level', level: title.id, name: 'synthetic-willow-419', permissions: [], scope: { kind: 'group', dimensions: { location: [location.id] } }, jobFields: { self: {}, others: { jobTitle: 'approval' } } })
 await api('change.decide', { request: bounded.id, state, decision: 'approve' }, 403)
 assert.equal((await profile(outside.person, day(60))).current.jobTitle, 'Present role')
 const scoped = await join('synthetic-willow-425', { locationId: location.id })
 await apply({ kind: 'level', level: editLevel.id, name: 'synthetic-willow-409', permissions: [], scope: { kind: 'group', dimensions: { location: [location.id] } }, jobFields: rules('edit') })
 const scopedWrite = async (person, value, effectiveFrom, status) => as(editor, 'job.field', { person: person.person, period: person.period, revision: (await period(person.person, person.period)).revision, field: 'jobTitle', value, effectiveFrom, reason: 'synthetic-willow-426' }, status)
 await scopedWrite(scoped, 'synthetic-willow-427', day(50))
 await scopedWrite(outside, 'synthetic-willow-427', day(50), 403)
 const movedLocation = await api('location.create', { name: 'synthetic-willow-428', timezone:'UTC' })
 await api('mover.schedule', { period: scoped.period, effectiveFrom: day(-1), reason: 'synthetic-willow-429', locationId: movedLocation.id })
 await scopedWrite(scoped, 'synthetic-willow-430', day(51), 403)
 assert.equal((await profile(scoped.person, day(51))).current.jobTitle, 'synthetic-willow-427', 'A mover removes exact-field authority immediately without altering approved history')
 console.log('ROLE-004 job writes: PASS — ten exact fields, native typed approval, immutable history, pay isolation, self/cycle/stale/scope/revocation fences')
 return { editor, requester, target, pending, editLevel, approvalLevel, schedule }
}
