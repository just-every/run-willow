// ROLE-001 personal-field slice, exercised through signed-in production HTTP doors.
import assert from 'node:assert/strict'
export async function personalFieldProof(h,owner,s) {
 const api=(path,body,status)=>h.api(path,owner,body,status)
 const employee=(path,body,status)=>h.api(path,s.employee.cookie,body,status)
 const hr=(path,body,status)=>h.api(path,s.hr.cookie,body,status)
 const fields=['preferredName','personal_email','phone','address','date_of_birth','emergency_contact']
 const read=()=>employee(`people/${s.employee.person}`)
 const value=(record,field)=>field==='preferredName'?record.preferredName:record.private[field]
 const review=plan=>api('level.preview',plan)
 const apply=async plan=>api('level.apply',{review:(await review(plan)).id})
 const create=async(name,selfFields)=>apply({kind:'level',name,permissions:[],selfFields})
 const assign=levels=>apply({kind:'assignment',member:s.employee.member,levels})
 const initial=await read()
 await api('person.update',{person:s.employee.person,revision:initial.revision,legalName:'Elena Patel',preferredName:'Elena',workEmail:initial.workEmail,employeeNumber:initial.employeeNumber??''})
 const current=await read()
 assert.deepEqual(Object.values((await employee('me')).selfWriteModes),fields.map(()=>'edit'),'No configured rows preserves every current self-write right')
 const approvalRules=Object.fromEntries(fields.map(field=>[field,'approval']))
 const level=await create('Personal changes reviewed by HR',approvalRules)
 const assignment=await review({kind:'assignment',member:s.employee.member,levels:[level.id]})
 assert.deepEqual(assignment.impact[0].added,[],'Personal modes add no fixed permission')
 assert.equal(assignment.impact[0].changedFields.length,fields.length)
 assert.deepEqual((await employee('me')).selfWriteModes,Object.fromEntries(fields.map(f=>[f,'edit'])),'Review has no side effect')
 await api('level.apply',{review:assignment.id})
 assert.deepEqual((await employee('me')).permissions,[])
 for(const [i,field] of fields.entries()) {
  const next={preferredName:'Elle',personal_email:'elena.patel@example.com',phone:'+1 512 555 0142',address:'1401 Willow Lane, Austin TX 78701',date_of_birth:'1991-05-12',emergency_contact:'Maya Patel +1 512 555 0162'}[field]
  const before=await read()
  const direct=field==='preferredName'?{preferredName:next}:{...before.private,[field]:next,private:true}
  await employee('person.update',{person:s.employee.person,revision:before.revision,...direct},403)
  const proposal=await employee('self.request',{kind:'personal',field,value:next})
  const saved=await employee(`self-changes/${proposal.id}`)
  assert.deepEqual(saved.before,{[field]:value(before,field)})
  assert.deepEqual(saved.after,{[field]:next})
  assert.equal(value(await read(),field),value(before,field),'Approval-required edits stay pending')
  assert.ok((await hr('self-changes')).some(c=>c.id===proposal.id),'Proposal enters the existing HR queue')
  await employee('self.decide',{change:proposal.id,decision:'approve',comment:'Self approval'},403)
  for(const who of ['managera','payroll']) await h.api(`self-changes/${proposal.id}`,s[who].cookie,undefined,404)
  await hr('self.decide',{change:proposal.id,decision:'approve',comment:'Reviewed personal revision'})
  assert.equal(value(await read(),field),next)
  await hr('self.decide',{change:proposal.id,decision:'approve',comment:'Replay'},409)
  assert.deepEqual((await employee(`self-changes/${proposal.id}`)).after,saved.after)
  assert.ok((await h.api('self-exceptions',s.payroll.cookie)).some(c=>c.id===proposal.id),'Approved field feeds the downstream metadata-only handoff')
 }
 for(const body of [{kind:'personal',field:'payAmount',value:'1'},{kind:'personal',field:'date_of_birth',value:'2026-02-30'},{kind:'personal',field:'phone',value:'Changed',permissions:['people.manage']}]) await employee('self.request',body,400)
 const blank=await employee('self.request',{kind:'personal',field:'phone',value:''})
 await hr('self.decide',{change:blank.id,decision:'approve',comment:'Clear contact'})
 assert.equal((await read()).private.phone,null)
 const stale=await employee('self.request',{kind:'personal',field:'phone',value:'Old proposal'})
 const ownerEdit=await read()
 await api('person.update',{person:s.employee.person,revision:ownerEdit.revision,private:true,...ownerEdit.private,phone:'Changed by owner'})
 await hr('self.decide',{change:stale.id,decision:'approve',comment:'Stale'},409)
 await hr('self.decide',{change:stale.id,decision:'reject',comment:'Submit current values'})
 const pending=await employee('self.request',{kind:'personal',field:'phone',value:'Revoked pending'})
 const change=await review({kind:'level',level:level.id,name:'Personal changes reviewed by HR',permissions:[],selfFields:{...approvalRules,phone:'view'}})
 assert.deepEqual(change.impact[0].changedFields,['phone'])
 await api('level.apply',{review:change.id})
 await employee('self.request',{kind:'personal',field:'phone',value:'Denied'},403)
 await hr('self.decide',{change:pending.id,decision:'approve',comment:'Current rights deny'},403)
 await hr('self.decide',{change:pending.id,decision:'reject',comment:'No longer authorized'})
 const edit=await create('Immediate phone only',{phone:'edit'})
 await assign([level.id,edit.id])
 assert.equal((await employee('me')).selfWriteModes.phone,'edit','Explicit assigned rights form a union')
 const record=await read()
 await employee('person.update',{person:s.employee.person,revision:record.revision,...record.private,private:true,phone:'Immediate union'})
 assert.equal((await read()).private.phone,'Immediate union')
 await assign([level.id])
 await employee('person.update',{person:s.employee.person,revision:(await read()).revision,private:true,phone:'Bypass via omitted protected values'},403)
 await assign([])
 assert.equal((await employee('me')).selfWriteModes.phone,'edit','Removing explicit modes restores the existing self-service baseline')
 assert.deepEqual((await read()).employment,current.employment)
 const audit=await api('audit')
 assert.ok(audit.some(e=>e.action==='level.level'&&JSON.stringify(e).includes('phone')))
 assert.ok(!JSON.stringify(await h.api(`people/${s.employee.person}`,s.managera.cookie)).includes('elena.patel@example.com'))
 return {level:level.id,approvalRules}
}
