// Native definition modes and bounded band/cycle reads, through the public doors.
import assert from 'node:assert/strict'
import { day } from './regression-fixture.mjs'
import { publishTemplate } from './publish-template.mjs'

export async function compensationDefinitionProof(h, owner, fx) {
 const { api, join } = fx
 const employer = (await api('me')).employer
 const apply = async plan => api('level.apply', { review: (await api('level.preview', plan)).id })
 const as = (who, path, body, status) => h.api(path, who.cookie, body, status)
 const member = async (number, extra = {}) => {
  const key = `synthetic-willow-${number}`, person = await join(key, extra)
  const ip = `192.0.2.${number - 800}`
  const response = await h.raw('/api/willow/access.give', { cookie: owner, body: { person: person.person }, ip })
  assert.equal(response.status, 200, 'Native access invitation')
  const access = await response.json()
  return { ...person, member: access.id, cookie: await h.signIn(`${key}@example.com`, { requested: true, ip }) }
 }
 await api('employer.configure', { ...employer, currency: 'USD' })
 try {
  const location = await api('location.create', { name: 'synthetic-willow-801', timezone: 'UTC' })
  const otherLocation = await api('location.create', { name: 'synthetic-willow-802', timezone: 'UTC' })
  const subject = await member(803, { jobTitle: 'synthetic-willow-804', locationId: location.id })
  const outside = await member(805, { jobTitle: 'synthetic-willow-806', locationId: otherLocation.id })
  const none = await member(807), viewer = await member(808), writer = await member(809), requester = await member(810), scoped = await member(811)
  const definition = async (name, mode, scope = { kind: 'everyone' }, self = {}) => apply({ kind: 'level', name, permissions: [], scope, compensationFields: { self, others: { bands: mode, cycles: mode } } })
  const view = await definition('synthetic-willow-812', 'view')
  const edit = await definition('synthetic-willow-813', 'edit')
  const approval = await definition('synthetic-willow-814', 'approval')
  const scope = { kind: 'group', dimensions: { location: [location.id] } }
  const scopedEdit = await definition('synthetic-willow-815', 'edit', scope)
  const self = await definition('synthetic-willow-816', 'none', { kind: 'everyone' }, { bands: 'view', cycles: 'view' })
  for (const [who, level] of [[viewer, view], [writer, edit], [requester, approval], [scoped, scopedEdit], [subject, self]]) await apply({ kind: 'assignment', member: who.member, levels: [level.id] })
  if (!(await api('custom-fields')).some(field => field.key === 'job_level')) await api('customField.define', { definition: { key: 'job_level', classification: 'general', label: 'synthetic-willow-817', type: 'text', required: false, effectiveFrom: day(-90), employeeRead: true, managerRead: true, retired: false, validation: { maxLength: 60 } } })
  for (const [person, value] of [[subject, 'synthetic-willow-818'], [outside, 'synthetic-willow-819']]) await api('customField.write', { person: person.person, effectiveFrom: day(-60), values: { job_level: value } })
  const bandValues = { jobTitle: 'synthetic-willow-804', level: 'synthetic-willow-818', location: location.id, basis: 'salary', effectiveFrom: day(-1), minimum: '70000', maximum: '90000' }
  const cycleValues = { name: 'synthetic-willow-820', kind: 'merit', effectiveFrom: day(30), budget: '10000' }
  await as(none, 'compensation', undefined, 403)
  await as(none, 'compensation.band', { ...bandValues, person: subject.person }, 403)
  await as(none, 'compensation.cycle', { ...cycleValues, person: subject.person }, 403)
  await as(viewer, 'compensation.band', { ...bandValues, person: subject.person }, 403)
  await as(viewer, 'compensation.cycle', { ...cycleValues, person: subject.person }, 403)
  await as(scoped, 'compensation.band', { ...bandValues, person: subject.person }, 403)
  await as(scoped, 'compensation.cycle', { ...cycleValues, person: subject.person }, 403)
  await as(writer, 'compensation.band', bandValues, 403)
  await as(writer, 'compensation.band', { ...bandValues, person: writer.person }, 403)
  const band = await as(writer, 'compensation.band', { ...bandValues, person: subject.person })
  const cycle = await as(writer, 'compensation.cycle', { ...cycleValues, person: subject.person })
  const hiddenBand = await api('compensation.band', { ...bandValues, jobTitle: 'synthetic-willow-806', level: 'synthetic-willow-819', location: otherLocation.id })
  const unrelated = await api('compensation.cycle', { ...cycleValues, name: 'synthetic-willow-821' })
  assert.ok((await as(viewer, 'compensation')).bands.some(row => row.id === band.id))
  assert.ok((await as(viewer, 'compensation')).bands.some(row => row.id === hiddenBand.id))
  const scopedHome = await as(scoped, 'compensation')
  assert.deepEqual(scopedHome.bands.map(row => row.id), [band.id], 'Scoped definition reads follow current job, job level and location')
  assert.ok(!scopedHome.cycles.some(row => row.id === cycle.id), 'A scoped cycle reader has no access to unrelated drafts')
  assert.ok((await as(subject, 'compensation')).bands.some(row => row.id === band.id), 'Self View reads only applicable definitions')
  await as(writer, 'compensation.budget', { cycle: cycle.id }, 403)
  await as(writer, 'compensation.publish', { cycle: cycle.id, review: 'synthetic-willow-822' }, 403)
  assert.deepEqual((await as(writer, 'me')).permissions, [], 'Definition maintenance grants neither salary nor publication authority')
  await api('compensation.budget', { cycle: cycle.id })
  for (const person of [subject, outside]) await api('compensation.propose', { cycle: cycle.id, person: person.person, percent: '1', note: 'synthetic-willow-823' })
  const detail = await as(scoped, `compensation/${cycle.id}`)
  assert.deepEqual(detail.rows.map(row => row.person_id), [subject.person])
  assert.equal(detail.rows[0].amount_cents, null)
  assert.equal(detail.cycle.budget_cents, null)
  assert.equal(detail.cycle.publication_json, null)
  await as(scoped, `compensation/${unrelated.id}`, undefined, 403)
  const whole = await as(viewer, `compensation/${cycle.id}`)
  assert.equal(whole.cycle.budget_cents, 1000000)
  assert.ok(whole.rows.every(row => row.amount_cents === null && row.previous_cents === null))
  const selfCycle = await as(subject, `compensation/${cycle.id}`)
  assert.deepEqual(selfCycle.rows.map(row => row.person_id), [subject.person])
  assert.equal(selfCycle.cycle.budget_cents, null)
  assert.equal(selfCycle.rows[0].amount_cents, null)

  const mover = await publishTemplate(h, owner, { name: 'synthetic-willow-824', kind: 'mover', taskTitle: ['synthetic-willow-825'], taskAssignee: ['hr'], taskDueDays: ['0'] })
  await api('change.chain', { requestType: 'compensation', template: mover.id, stepRole: ['hr'] })
  const approve = async (id, status) => api('change.decide', { request: id, state: (await api(`change-requests/${id}`)).state, decision: 'approve' }, status)
  const proposedBand = await as(requester, 'compensation.band', { ...bandValues, effectiveFrom: day(5), minimum: '72000', person: subject.person })
  assert.equal(proposedBand.type, 'compensation')
  const bandRequest = await as(requester, `change-requests/${proposedBand.id}`)
  assert.equal(bandRequest.editCompensation.kind, 'definition')
  assert.equal(bandRequest.editCompensation.values.values.minimum, '72000.00')
  await as(requester, 'compensation.definition.resubmit', { ...bandValues, definitionKind: 'bands', person: subject.person, effectiveFrom: day(5), minimum: '73000', request: proposedBand.id, state: bandRequest.state, reason: 'synthetic-willow-829' })
  const editedBand = await as(requester, `change-requests/${proposedBand.id}`)
  assert.equal(editedBand.editCompensation.values.values.minimum, '73000.00')
  assert.equal(editedBand.editCompensation.values.values.maximum, '90000.00')
  const bandPage = await (await h.raw(`/app/changes/${proposedBand.id}`, { cookie: requester.cookie })).text()
  assert.ok(bandPage.includes('/app/do/compensation.definition.resubmit') && !bandPage.includes('/app/do/change.edit'))
  assert.ok(!(await as(viewer, 'compensation')).bands.some(row => row.effective_from === day(5) && row.job_title === bandValues.jobTitle), 'Approval mode does not publish a band early')
  const publishedBand = await approve(proposedBand.id)
  assert.ok((await as(viewer, 'compensation')).bands.some(row => row.id === publishedBand.result.id && row.minimum_cents === 7300000))
  const proposedCycle = await as(requester, 'compensation.cycle', { ...cycleValues, name: 'synthetic-willow-826', person: subject.person })
  const cycleRequest = await as(requester, `change-requests/${proposedCycle.id}`)
  await as(requester, 'compensation.definition.resubmit', { ...cycleValues, name: 'synthetic-willow-826', budget: '11000', definitionKind: 'cycles', person: subject.person, request: proposedCycle.id, state: cycleRequest.state, reason: 'synthetic-willow-830' })
  const editedCycle = await as(requester, `change-requests/${proposedCycle.id}`)
  assert.equal(editedCycle.editCompensation.values.values.kind, cycleValues.kind)
  assert.equal(editedCycle.editCompensation.values.values.budget, '11000.00')
  assert.ok(!(await as(viewer, 'compensation')).cycles.some(row => row.name === 'synthetic-willow-826'))
  const publishedCycle = await approve(proposedCycle.id)
  const newCycle = (await as(viewer, 'compensation')).cycles.find(row => row.id === publishedCycle.result.id)
  assert.equal(newCycle.status, 'draft', 'Approving a definition grants no budget approval')
  assert.equal(newCycle.budget_cents, 1100000)
  await as(requester, 'compensation.budget', { cycle: newCycle.id }, 403)
  const revoked = await as(requester, 'compensation.band', { ...bandValues, effectiveFrom: day(6), person: subject.person })
  await apply({ kind: 'assignment', member: requester.member, levels: [] })
  const withheld = await as(requester, `change-requests/${revoked.id}`)
  assert.equal(withheld.editCompensation, undefined)
  assert.equal(withheld.mayEdit, false)
  assert.ok(withheld.history.every(event => event.comment === null))
  await as(requester, 'compensation.definition.resubmit', { ...bandValues, definitionKind: 'bands', effectiveFrom: day(6), request: revoked.id, state: withheld.state, reason: 'synthetic-willow-831' }, 403)
  await approve(revoked.id, 403)
  assert.equal((await api(`change-requests/${revoked.id}`)).status, 'pending')
  await apply({ kind: 'assignment', member: requester.member, levels: [approval.id] })
  const narrowed = await as(requester, 'compensation.cycle', { ...cycleValues, name: 'synthetic-willow-827', person: subject.person })
  await apply({ kind: 'level', level: approval.id, name: 'synthetic-willow-814', permissions: [], scope, compensationFields: { self: {}, others: { bands: 'approval', cycles: 'approval' } } })
  await approve(narrowed.id, 403)
  await as(requester, 'compensation.band', { ...bandValues, person: subject.person }, 403)
  await api('mover.schedule', { period: subject.period, effectiveFrom: day(-2), locationId: otherLocation.id, reason: 'synthetic-willow-828' })
  assert.ok(!(await as(scoped, 'compensation')).bands.some(row => row.id === band.id))
  assert.ok(!(await as(scoped, 'compensation')).cycles.some(row => row.id === cycle.id), 'Current scope controls cycle participation reads after a mover')
  console.log('ROLE-005 definitions: PASS — default/view/edit/approval, everyone maintenance boundary, applicable scoped/self reads, typed approval, revocation and no salary/budget publication escalation')
 } finally {
  await api('employer.configure', employer)
 }
}
