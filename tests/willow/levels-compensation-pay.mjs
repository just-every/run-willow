// ROLE-005 salary custody and explicit current-authority reads through public doors.
import assert from 'node:assert/strict'
import { day } from './regression-fixture.mjs'
import { publishTemplate } from './publish-template.mjs'
import { readZip } from './export-reader.mjs'

export async function compensationPayProof(h, owner, fx) {
 const api = (path, body, status) => h.api(path, owner, body, status)
 const apply = async plan => api('level.apply', { review: (await api('level.preview', plan)).id })
 const near = await api('location.create', { name: 'synthetic-willow-601', timezone: 'UTC' })
 const far = await api('location.create', { name: 'synthetic-willow-602', timezone: 'UTC' })
 const person = async number => {
  const key = `synthetic-willow-${number}`, joined = await fx.join(key, { locationId: near.id, payAmount: '93457.81' })
  const response = await h.raw('/api/willow/access.give', { cookie: owner, body: { person: joined.person }, ip: `10.6.1.${number - 600}` })
  assert.equal(response.status, 200, await response.clone().text())
  return { ...joined, member: (await response.json()).id, cookie: await h.signIn(`${key}@example.com`, { requested: true, ip: `10.6.2.${number - 600}` }) }
 }
 const subject = await person(603), reader = await person(604), writer = await person(605), requester = await person(606)
 const outside = await fx.join('synthetic-willow-607', { locationId: far.id, payAmount: '97651.23' })
 const scope = { kind: 'group', dimensions: { location: [near.id] } }
 const as = (who, path, body, status) => h.api(path, who.cookie, body, status)
 const read = (who, id = subject.person, date) => as(who, `people/${id}${date ? `?asOf=${date}` : ''}`)
 const terms = profile => (profile.employment ?? []).flatMap(period => period.terms)
 const current = profile => terms(profile).find(term => term.inForce)
 const source = async id => (await api(`people/${id}`)).employment.find(period => period.id === (id === subject.person ? subject.period : writer.period))
 const names = ['pay', 'history', 'bands', 'bonus', 'equity', 'cycles']
 const plan = { kind: 'level', name: 'synthetic-willow-608', permissions: ['reports.read'], scope, compensationFields: { self: {}, others: {} } }
 const viewing = await apply(plan)
 await apply({ kind: 'assignment', member: reader.member, levels: [viewing.id] })
 for (const [who, id] of [[subject, subject.person], [reader, subject.person]]) {
  const record = await read(who, id)
  assert.equal(record.pay, undefined)
  assert.ok(terms(record).every(term => term.pay === undefined))
  assert.ok(record.compensation.withheld.includes('pay'))
  const page = await (await h.raw(`/app/people/${id}`, { cookie: who.cookie })).text()
  assert.ok(!page.includes('93457.81') && !page.includes('9345781'))
 }
 // Each section is an independent read source; history alone grants no salary.
 for (const field of names) {
  await apply({ ...plan, level: viewing.id, compensationFields: { self: {}, others: { [field]: 'view' } } })
  const record = await read(reader)
  for (const other of names) assert.equal(record.compensationFields[other], other === field, `${field} does not grant ${other}`)
  assert.equal(current(record)?.pay?.amountCents, field === 'pay' ? 9345781 : undefined)
  assert.equal((await read(reader, outside.person)).pay, undefined, 'Another location never inherits a field')
 }
 const selfView = await apply({ kind: 'level', name: 'synthetic-willow-609', permissions: [], scope: { kind: 'group', dimensions: { location: [far.id] } }, compensationFields: { self: { pay: 'view' }, others: {} } })
 await apply({ kind: 'assignment', member: subject.member, levels: [selfView.id] })
 assert.equal(current(await read(subject))?.pay?.amountCents, 9345781, 'Self View is explicit and independent of the level scope')
 const ownSource = await source(subject.person)
 await as(subject, 'compensation.pay', { person: subject.person, period: subject.period, revision: ownSource.revision, effectiveFrom: day(5), payBasis: 'salary', payAmount: '84567.19', reason: 'synthetic-willow-610' }, 403)
 const editing = await apply({ kind: 'level', name: 'synthetic-willow-611', permissions: [], scope, compensationFields: { self: {}, others: { pay: 'edit' } } })
 const approval = await apply({ kind: 'level', name: 'synthetic-willow-612', permissions: [], scope, compensationFields: { self: {}, others: { pay: 'approval' } } })
 for (const [who, level] of [[writer, editing], [requester, approval]]) await apply({ kind: 'assignment', member: who.member, levels: [level.id] })
 const pay = { person: subject.person, period: subject.period, revision: ownSource.revision, effectiveFrom: day(5), payBasis: 'salary', payAmount: '84567.19', reason: 'synthetic-willow-613' }
 await as(reader, 'compensation.pay', pay, 403)
 await as(requester, 'compensation.pay', pay, 403)
 await as(writer, 'compensation.pay', { ...pay, person: writer.person, period: writer.period, revision: (await source(writer.person)).revision }, 403)
 await as(writer, 'compensation.pay', { ...pay, person: outside.person, period: outside.period }, 403)
 const before = await api(`people/${subject.person}`)
 const saved = await as(writer, 'compensation.pay', pay)
 await as(writer, 'compensation.pay', pay, 409)
 const after = await api(`people/${subject.person}`)
 assert.equal(terms(after).length, terms(before).length + 1)
 const written = terms(after).find(term => term.id === saved.terms)
 assert.deepEqual(written.pay, { basis: 'salary', amountCents: 8456719, currency: 'AUD' })
 for (const key of ['jobTitle', 'department', 'location', 'manager', 'schedule', 'fte']) assert.deepEqual(written[key], current(before)[key], `Pay-only edit preserves ${key}`)
 await apply({ ...plan, level: viewing.id, compensationFields: { self: {}, others: { pay: 'view' } } })
 assert.equal(current(await read(reader, subject.person, day(4))).pay.amountCents, 9345781)
 assert.equal(current(await read(reader, subject.person, day(5))).pay, undefined, 'Current-pay View cannot be used to read another dated version')
 assert.equal(terms(await read(reader, subject.person, day(5))).filter(term => term.pay).length, 1)
 await apply({ ...plan, level: viewing.id, compensationFields: { self: {}, others: { pay: 'view', history: 'view' } } })
 assert.equal(terms(await read(reader, subject.person, day(5))).filter(term => term.pay).length, 2)
 assert.equal(current(await read(reader, subject.person, day(4))).pay.amountCents, 9345781)
 assert.equal(current(await read(reader, subject.person, day(5))).pay.amountCents, 8456719)
 await apply({ ...plan, level: viewing.id, compensationFields: { self: {}, others: { history: 'view' } } })
 const historyOnly = await read(reader)
 assert.equal(current(historyOnly).pay, undefined, 'History alone never grants pay currently in force')
 assert.equal(historyOnly.compensation.payRecords.find(term=>term.id===saved.terms).effectiveFrom,day(5),'Salary history carries its own effective date')
 assert.equal(terms(historyOnly).find(term => term.id === saved.terms).pay.amountCents, 8456719, 'History can read a different recorded version independently')
 await apply({ ...plan, level: viewing.id, compensationFields: { self: {}, others: { pay: 'view', history: 'view' } } })
 const context = await as(reader, `context/${subject.person}?asOf=${day(5)}`)
 assert.equal(current(context.record).pay.amountCents, 8456719)
 const preview = await api(`preview?member=${reader.member}&person=${subject.person}`)
 assert.equal(current(preview.view).pay.amountCents, 9345781)
 for (const format of ['csv', 'xlsx', 'zip']) {
  const response = await h.raw(`/app/exports/employees.${format}?scope=organization&person=${subject.person}&asOf=${day(5)}&fields=name,payAmount,phone${format === 'zip' ? '&history=employment' : ''}`, { cookie: reader.cookie })
  assert.equal(response.status, 200)
  const bytes = Buffer.from(await response.arrayBuffer()), text = format === 'csv' ? bytes.toString() : [...readZip(bytes).values()].map(value => value.toString()).join('\n')
  assert.ok(text.includes('84567.19') || text.includes('8456719'))
  assert.ok(!text.includes('PRIVATE-synthetic-willow-603'))
 }
 await as(reader, 'payroll', undefined, 403)
 const batch = await api('payroll.draft', { periodStart: day(0), periodEnd: day(40) })
 const handoff = await as(fx.staff.payroll, `payroll/${batch.id}`)
 assert.ok(JSON.stringify(handoff).replaceAll(',', '').includes('84567.19'))
 await api('payroll.discard', { batch: batch.id })
 const mover = await publishTemplate(h, owner, { name: 'synthetic-willow-614', kind: 'mover', taskTitle: ['synthetic-willow-615'], taskAssignee: ['hr'], taskDueDays: ['0'] })
 await api('change.chain', { requestType: 'compensation', template: mover.id, stepRole: ['hr'] })
 const propose = () => as(requester, 'change.request', { person: subject.person, effectiveFrom: day(10), payBasis: 'salary', payAmount: '85678.23', reason: 'synthetic-willow-616' })
 const decide = async (request, status) => api('change.decide', { request: request.id, state: (await api(`change-requests/${request.id}`)).state, decision: 'approve' }, status)
 const pending = await propose()
 assert.equal(pending.type, 'compensation')
 assert.equal(terms(await api(`people/${subject.person}`)).length, 2)
 await decide(pending)
 assert.equal(current(await read(reader, subject.person, day(10))).pay.amountCents, 8567823)
 const stale = await as(requester, 'change.request', { person: subject.person, effectiveFrom: day(15), payIncreasePercent: '2', reason: 'synthetic-willow-617' })
 await as(writer, 'compensation.pay', { ...pay, revision: (await source(subject.person)).revision, effectiveFrom: day(12), payAmount: '86789.34' })
 await decide(stale, 409)
 const revoked = await as(requester, 'change.request', { person: subject.person, effectiveFrom: day(20), payIncreasePercent: '2', reason: 'synthetic-willow-618' })
 await apply({ kind: 'assignment', member: requester.member, levels: [] })
 await decide(revoked, 403)
 await apply({ ...plan, level: viewing.id, compensationFields: { self: {}, others: {} } })
 assert.equal((await read(reader)).pay, undefined)
 assert.ok(!JSON.stringify(await as(reader, `context/${subject.person}?asOf=${day(10)}`)).includes('8567823'))
 assert.ok(terms((await api(`preview?member=${reader.member}&person=${subject.person}`)).view).every(term => term.pay === undefined))
 const csv = await (await h.raw(`/app/exports/employees.csv?scope=organization&person=${subject.person}&asOf=${day(10)}&fields=name,payAmount`, { cookie: reader.cookie })).text()
 assert.ok(!csv.includes('85678.23'))
 // Historical salary writes cannot change the separate pay-in-force field.
 await api('mover.schedule',{period:subject.period,effectiveFrom:day(-2),payBasis:'salary',payAmount:'90234.56',reason:'synthetic-willow-619'})
 await apply({kind:'level',level:editing.id,name:'synthetic-willow-611',permissions:[],scope,compensationFields:{self:{},others:{history:'edit'}}})
 const historical={...pay,revision:(await source(subject.person)).revision,effectiveFrom:day(-10),payAmount:'80123.45'}
 await as(writer,'compensation.pay',historical)
 assert.equal(current(await api(`people/${subject.person}`)).pay.amountCents,9023456)
 assert.equal(current(await api(`people/${subject.person}?asOf=${day(-10)}`)).pay.amountCents,8012345)
 await as(writer,'compensation.pay',{...historical,revision:(await source(subject.person)).revision,effectiveFrom:day(1)},403)
 await apply({kind:'level',level:approval.id,name:'synthetic-willow-612',permissions:[],scope,compensationFields:{self:{},others:{history:'approval'}}})
 await apply({kind:'assignment',member:requester.member,levels:[approval.id]})
 const historicalRequest=await as(requester,'change.request',{person:subject.person,effectiveFrom:day(-7),payBasis:'salary',payAmount:'81234.57',reason:'synthetic-willow-620'})
 await decide(historicalRequest)
 assert.equal(current(await api(`people/${subject.person}`)).pay.amountCents,9023456)
 assert.equal(current(await api(`people/${subject.person}?asOf=${day(-7)}`)).pay.amountCents,8123457)
 console.log('ROLE-005 salary: PASS — explicit self reads, all section boundaries, scoped exact edits, pay/history dates, exports/preview/context/payroll and typed approval/revocation')
}
