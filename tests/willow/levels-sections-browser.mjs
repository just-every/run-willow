// ROLE-005/006: native forms and resulting records, with a fresh fixture runner.
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { evidenceDirectory } from './evidence.mjs'
import { day } from './regression-fixture.mjs'
import { publishTemplate } from './publish-template.mjs'

const compensationLabels = { pay: 'Pay in force', history: 'Pay history', bands: 'Compensation bands', bonus: 'Bonus records', equity: 'Equity records', cycles: 'Compensation cycles' }
const leaveLabels = { balances: 'Leave balances', ledger: 'Leave ledger', requests: 'Leave requests', calendar: 'Absence calendar', policies: 'Leave policies' }
const viewModes = { pay: 'view', bonus: 'view', equity: 'view' }
const compensationSection = page => page.locator('section.facet-compensation')
const leaveSection = page => page.locator('section.facet-leave')
const details = (page, within, summary) => within.locator('details').filter({ has: page.locator('summary').filter({ hasText: summary }) }).first()
const currentPay = profile => (profile.employment ?? []).flatMap(period => period.terms).find(term => term.inForce)?.pay

export async function sectionBrowserProof(h, owner, fx) {
 if (process.env.WILLOW_LEVELS_BROWSER !== '1') return
 assert.ok(process.platform !== 'darwin' || process.env.WILLOW_PLAYWRIGHT_PATH, 'Use the current Playwright on macOS')
 const { chromium } = await import(process.env.WILLOW_PLAYWRIGHT_PATH ? pathToFileURL(process.env.WILLOW_PLAYWRIGHT_PATH).href : '@playwright/test')
 const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] })
 const sessions = []
 const open = async cookie => {
  const context = await browser.newContext({ ignoreHTTPSErrors: true })
  sessions.push(context)
  await context.addCookies(cookie.split('; ').map(item => ({ name: item.slice(0, item.indexOf('=')), value: item.slice(item.indexOf('=') + 1), url: h.origin })))
  return context.newPage()
 }
 try {
  const admin = await open(owner), reader = await open(fx.staff.managerb.cookie)
  const api = (path, body, status) => h.api(path, owner, body, status)
  const asReader = (path, body, status) => h.api(path, fx.staff.managerb.cookie, body, status)
  const apply = async plan => api('level.apply', { review: (await api('level.preview', plan)).id })
  const template = await publishTemplate(h, owner, { name: 'synthetic-willow-8100', kind: 'mover', taskTitle: ['synthetic-willow-8101'], taskAssignee: ['hr'], taskDueDays: ['0'] })
  await api('change.chain', { requestType: 'compensation', template: template.id, stepRole: ['hr'] })
  for (const [index, width] of [1440, 390].entries()) {
   for (const page of [admin, reader]) await page.setViewportSize({ width, height: 1000 })
   const capture = async (page, name) => {
    await page.evaluate(() => document.fonts.ready)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name} fits ${width}`)
    await page.screenshot({ path: `${evidenceDirectory}/${name}-${width}.png`, fullPage: true })
   }
   const visit = async (page, path) => assert.equal((await page.goto(h.origin + path)).status(), 200, path)
   const submit = async (page, container, button) => {
    await container.getByRole('button', { name: button, exact: true }).click()
    await page.waitForURL(url => url.searchParams.has('notice') || url.searchParams.has('error'))
    assert.ok(!new URL(page.url()).searchParams.has('error'), page.url())
   }
   const n = 8120 + index * 20
   await apply({ kind: 'assignment', member: fx.staff.managerb.member, levels: [] })
   const near = await api('location.create', { name: `synthetic-willow-${n}`, timezone: 'UTC' })
   const far = await api('location.create', { name: `synthetic-willow-${n + 1}`, timezone: 'UTC' })
   const department = await api('department.create', { name: `synthetic-willow-${n + 2}` })
   const target = await fx.join(`synthetic-willow-${n + 3}`, { locationId: near.id, departmentId: department.id, payAmount: '93457.81' })
   const peer = await fx.join(`synthetic-willow-${n + 4}`, { locationId: far.id, departmentId: department.id, payAmount: '97651.23' })
   const account = await fx.account(target.period), peerAccount = await fx.account(peer.period)
   const readTarget = () => api(`people/${target.person}`)
   const targetAccount = async () => (await readTarget()).leave.accounts.find(row => row.id === account)
   await api('compensation.record', { person: target.person, kind: 'bonus', effectiveDate: day(0), amount: '250.05', currency: 'AUD', note: `synthetic-willow-${n + 5}` })
   await api('compensation.record', { person: target.person, kind: 'equity', effectiveDate: day(0), units: '42.125', security: `synthetic-willow-${n + 6}`, note: `synthetic-willow-${n + 7}` })
   const levelName = `synthetic-willow-${n + 8}`
   const level = await apply({ kind: 'level', name: levelName, permissions: [], scope: { kind: 'group', dimensions: { location: [near.id] } } })
   await apply({ kind: 'assignment', member: fx.staff.managerb.member, levels: [level.id] })
   const updateLevel = async (compensation, leave, evidence) => {
    await visit(admin, '/app/access')
    const editor = details(admin, admin, new RegExp(`^${levelName} ·`))
    await editor.locator('summary').first().click()
    for (const [key, label] of Object.entries(compensationLabels)) await editor.getByLabel(`Compensation about others: ${label}`, { exact: true }).selectOption(compensation[key] ?? 'none')
    for (const [key, label] of Object.entries(leaveLabels)) await editor.getByLabel(`Leave about others: ${label}`, { exact: true }).selectOption(leave[key] ?? 'none')
    if (evidence) await capture(admin, 'ROLE-005-section-level-matrix')
    await editor.getByRole('button', { name: 'Review level', exact: true }).click()
    await admin.waitForURL(url => url.searchParams.has('levelReview') || url.searchParams.has('error'))
    assert.ok(!new URL(admin.url()).searchParams.has('error'), admin.url())
    if (evidence) await capture(admin, 'ROLE-005-section-level-review')
    await submit(admin, admin.locator('form[action="/app/do/level.apply"]'), 'Apply reviewed change')
   }

   await visit(reader, `/app/people/${target.person}`)
   assert.ok((await compensationSection(reader).innerText()).includes('Withheld'))
   assert.equal(await compensationSection(reader).locator('form').count(), 0)
   assert.ok(!(await reader.locator('body').innerText()).includes('93,457.81'))
   await capture(reader, 'ROLE-005-no-access-withheld')
   await updateLevel(viewModes, { balances: 'view' }, true)
   await visit(reader, `/app/people/${target.person}`)
   const viewing = await compensationSection(reader).innerText()
   for (const value of ['93,457.81', '250.05', '42.125']) assert.ok(viewing.includes(value), value)
   assert.equal(await compensationSection(reader).locator('form').count(), 0)
   await capture(reader, 'ROLE-005-scoped-pay-awards-view')
   assert.equal(await leaveSection(reader).locator('form').count(), 0)
   assert.equal(await leaveSection(reader).locator('details[id^="ledger-"]').count(), 0)
   assert.ok((await leaveSection(reader).innerText()).includes(`${((await targetAccount()).balanceMinutes / 60).toFixed(2)} hours`))
   await capture(reader, 'ROLE-006-balance-view-no-write')
   await visit(reader, `/app/people/${peer.person}`)
   assert.ok(!(await compensationSection(reader).innerText()).includes('97,651.23'))
   assert.equal(await leaveSection(reader).count(), 0)
   await capture(reader, 'ROLE-005-outside-scope-withheld')

   await updateLevel({ pay: 'edit', bonus: 'edit', equity: 'edit', history: 'view' }, { balances: 'view' })
   await visit(reader, `/app/people/${target.person}`)
   const salary = details(reader, compensationSection(reader), /^Schedule a pay change$/)
   await salary.locator('summary').click()
   await salary.getByLabel('Effective from', { exact: true }).fill(day(0))
   await salary.getByLabel('Pay basis', { exact: true }).selectOption('salary')
   await salary.getByLabel('Pay amount', { exact: true }).fill('84567.19')
   await salary.getByLabel('Reason', { exact: true }).fill(`synthetic-willow-${n + 9}`)
   await capture(reader, 'ROLE-005-exact-pay-edit-form')
   await submit(reader, salary, 'Schedule pay change')
   assert.equal(currentPay(await readTarget()).amountCents, 8456719)
   await capture(reader, 'ROLE-005-exact-pay-edit-end-state')
   for (const kind of ['bonus', 'equity']) {
    await visit(reader, `/app/people/${target.person}`)
    const award = details(reader, compensationSection(reader), new RegExp(`^Record ${kind}$`))
    await award.locator('summary').click()
    await award.getByLabel('Effective date', { exact: true }).fill(day(0))
    if (kind === 'bonus') {
     await award.getByLabel('Bonus amount', { exact: true }).fill('315.75')
     await award.getByLabel('Currency', { exact: true }).fill('AUD')
    } else {
     await award.getByLabel('Equity units', { exact: true }).fill('52.125001')
     await award.getByLabel('Security or share class', { exact: true }).fill(`synthetic-willow-${n + 10}`)
    }
    await award.getByLabel('Award note', { exact: true }).fill(`synthetic-willow-${n + 11}`)
    await capture(reader, `ROLE-005-${kind}-edit-form`)
    await submit(reader, award, `Save ${kind} record`)
   }
   const written = (await readTarget()).compensationRecords
   assert.ok(written.bonus.some(row => row.amountCents === 31575))
   assert.ok(written.equity.some(row => row.units === '52.125001'))
   await capture(reader, 'ROLE-005-awards-edit-end-state')

   await updateLevel({ pay: 'approval', bonus: 'approval', equity: 'approval' }, { balances: 'view' })
   const decline = async (request, kind) => {
    assert.equal((await api(`change-requests/${request}`)).status, 'pending')
    await capture(reader, `ROLE-005-${kind}-approval-pending`)
    await visit(admin, `/app/changes/${request}`)
    const decision = admin.locator('form[action="/app/do/change.decide"]')
    await decision.getByLabel('Decision', { exact: true }).selectOption('decline')
    await decision.getByLabel('Comment (required to send back)', { exact: true }).fill(`synthetic-willow-${n + 12}`)
    await submit(admin, decision, 'Record decision')
    assert.equal((await api(`change-requests/${request}`)).status, 'declined')
    await reader.reload()
    await capture(reader, `ROLE-005-${kind}-approval-declined`)
   }
   await visit(reader, `/app/people/${target.person}`)
   const payRequest = details(reader, compensationSection(reader), /^Request a pay change$/)
   await payRequest.locator('summary').click()
   await payRequest.getByLabel('Effective from', { exact: true }).fill(day(2))
   await payRequest.getByLabel('Pay basis', { exact: true }).selectOption('salary')
   await payRequest.getByLabel('Pay amount', { exact: true }).fill('85678.23')
   await payRequest.getByLabel('Reason', { exact: true }).fill(`synthetic-willow-${n + 13}`)
   await submit(reader, payRequest, 'Submit pay request')
   assert.equal(currentPay(await readTarget()).amountCents, 8456719, 'A pending salary request leaves native pay unchanged')
   const payResubmit = reader.locator('form[action="/app/do/change.edit"]')
   assert.equal(await payResubmit.getByLabel('Pay amount', { exact: true }).inputValue(), '85678.23')
   assert.equal(await payResubmit.getByLabel('Pay basis', { exact: true }).inputValue(), 'salary')
   await payResubmit.getByLabel('Pay amount', { exact: true }).fill('85679.34')
   await capture(reader, 'ROLE-005-pay-native-resubmit-form')
   await submit(reader, payResubmit, 'Resubmit compensation request')
   assert.equal((await asReader(`change-requests/${new URL(reader.url()).pathname.split('/').at(-1)}`)).editCompensation.values.pay.amount, '85679.34')
   assert.equal(currentPay(await readTarget()).amountCents, 8456719)
   await decline(new URL(reader.url()).pathname.split('/').at(-1), 'pay')
   assert.equal(currentPay(await readTarget()).amountCents, 8456719)
   await visit(reader, `/app/people/${target.person}`)
   const awardRequest = details(reader, compensationSection(reader), /^Record bonus · approval required$/)
   await awardRequest.locator('summary').click()
   await awardRequest.getByLabel('Effective date', { exact: true }).fill(day(3))
   await awardRequest.getByLabel('Bonus amount', { exact: true }).fill('777.77')
   await awardRequest.getByLabel('Currency', { exact: true }).fill('AUD')
   await awardRequest.getByLabel('Reason for approval', { exact: true }).fill(`synthetic-willow-${n + 14}`)
   const awardsBefore = (await readTarget()).compensationRecords
   await submit(reader, awardRequest, 'Request bonus record')
   assert.deepEqual((await readTarget()).compensationRecords, awardsBefore)
   const awardRequestId = new URL(reader.url()).pathname.split('/').at(-1)
   const resubmit = reader.locator('form[action="/app/do/compensation.record.resubmit"]')
   assert.equal(await resubmit.getByLabel('Bonus amount', { exact: true }).inputValue(), '777.77')
   assert.equal(await resubmit.getByLabel('Currency', { exact: true }).inputValue(), 'AUD')
   await resubmit.getByLabel('Bonus amount', { exact: true }).fill('778.88')
   await resubmit.getByLabel('Award note', { exact: true }).fill(`synthetic-willow-${n + 18}`)
   await capture(reader, 'ROLE-005-award-native-resubmit-form')
   await submit(reader, resubmit, 'Resubmit compensation request')
   assert.equal((await asReader(`change-requests/${awardRequestId}`)).editCompensation.values.amount, '778.88')
   assert.deepEqual((await readTarget()).compensationRecords, awardsBefore)
   await capture(reader, 'ROLE-005-award-resubmitted-pending')
   await decline(new URL(reader.url()).pathname.split('/').at(-1), 'award')
   assert.deepEqual((await readTarget()).compensationRecords, awardsBefore)
   await updateLevel({}, { balances: 'view' })
   await visit(reader, `/app/people/${target.person}`)
   assert.equal(await compensationSection(reader).locator('form').count(), 0)
   for (const value of ['84,567.19', '315.75', '52.125001']) assert.ok(!(await compensationSection(reader).innerText()).includes(value))
   await capture(reader, 'ROLE-005-compensation-revoked')

   await updateLevel({}, { balances: 'approval', ledger: 'view', requests: 'approval', calendar: 'view' })
   await visit(reader, `/app/people/${target.person}`)
   const before = await targetAccount(), overrideNote = `synthetic-willow-${n + 15}`
   const override = details(reader, leaveSection(reader), /^Propose balance override$/)
   await override.locator('summary').click()
   await override.getByLabel('Adjustment (hours, signed)', { exact: true }).fill('1.5')
   await override.getByLabel('Effective date', { exact: true }).fill(day(0))
   await override.getByLabel('Reason', { exact: true }).fill(overrideNote)
   await capture(reader, 'ROLE-006-adjustment-request-form')
   await submit(reader, override, 'Request owner approval')
   assert.deepEqual(await targetAccount(), before)
   await visit(admin, '/app/leave')
   const overrideRow = admin.locator('#overrides tbody tr').filter({ hasText: overrideNote })
   assert.equal(await overrideRow.locator('form[action="/app/do/leave.override.decide"]').count(), 2)
   await capture(admin, 'ROLE-006-adjustment-pending-owner-decision')
   await submit(admin, overrideRow, 'Approve override')
   const adjusted = await targetAccount()
   assert.equal(adjusted.balanceMinutes, before.balanceMinutes + 90)
   assert.equal(adjusted.ledger.length, before.ledger.length + 1)
   await visit(reader, `/app/people/${target.person}`)
   const ledger = leaveSection(reader).locator(`details#ledger-${account}`)
   await ledger.locator('summary').click()
   assert.ok((await ledger.innerText()).includes(overrideNote))
   await capture(reader, 'ROLE-006-approved-adjustment-ledger')

   const absenceDate = day(20 + index), confidential = `synthetic-willow-${n + 16}`
   const peerRequest = await api('leave.request', { account: peerAccount, startDate: absenceDate, endDate: absenceDate, reason: confidential })
   const behalf = details(reader, leaveSection(reader), /^Request leave on behalf$/)
   await behalf.locator('summary').click()
   await behalf.getByLabel('First day', { exact: true }).fill(absenceDate)
   await behalf.getByLabel('Last day', { exact: true }).fill(absenceDate)
   await behalf.getByLabel('Reason (confidential)', { exact: true }).fill(`synthetic-willow-${n + 17}`)
   await capture(reader, 'ROLE-006-request-on-behalf-form')
   await submit(reader, behalf, 'Submit leave request')
   const leaveRequest = new URL(reader.url()).pathname.split('/').at(-1)
   assert.equal((await api(`leave/${leaveRequest}`)).status, 'pending')
   assert.equal((await asReader(`leave/${leaveRequest}`)).canDecide, false)
   assert.equal(await reader.locator('form[action="/app/do/leave.decide"]').count(), 0)
   assert.ok((await reader.locator('body').innerText()).includes(`synthetic-willow-${n + 4}`))
   assert.ok(!(await reader.locator('body').innerText()).includes(confidential))
   assert.ok(!(await reader.locator('body').innerText()).includes(`synthetic-willow-${n + 17}`))
   await capture(reader, 'ROLE-006-on-behalf-pending-with-coverage')
   await updateLevel({}, { calendar: 'view' })
   await visit(reader, `/app/people/${target.person}`)
   const calendarOnly = (await asReader(`people/${target.person}`)).leave
   assert.deepEqual(calendarOnly.accounts, [])
   assert.deepEqual(calendarOnly.requests, [])
   assert.ok(calendarOnly.calendar.length)
   assert.equal(await leaveSection(reader).locator('form').count(), 0)
   assert.equal(await leaveSection(reader).locator('details[id^="ledger-"]').count(), 0)
   assert.ok(!(await leaveSection(reader).innerText()).includes('Balance:'))
   const quote = await asReader(`quote?account=${account}&startDate=${absenceDate}&endDate=${absenceDate}`)
   assert.deepEqual(Object.keys(quote).sort(), ['coverage', 'withheld'])
   assert.ok(quote.coverage.some(row => row.name === `synthetic-willow-${n + 4}`))
   for (const row of quote.coverage) assert.deepEqual(Object.keys(row).sort(), ['endDate', 'name', 'startDate', 'status'])
   await asReader(`leave/${peerRequest.id}`, undefined, 404)
   await capture(reader, 'ROLE-006-coverage-only')
  }
  console.log('ROLE-005/006 native browser: PASS — matrices/reviews, scoped View and Withheld, pay/award Edit, pending/declined approvals, revocation, balance-only View, owner-approved ledger adjustment, on-behalf request and coverage-only at 1440/390')
 } finally {
  for (const context of sessions) await context.close()
  await browser.close()
 }
}
