// ROLE-011 decision routing uses real levels, native requests, work and decisions.
import assert from 'node:assert/strict'
import { day } from './regression-fixture.mjs'
import { publishTemplate } from './publish-template.mjs'

export async function approvalRoutingProof(h, owner, fx) {
 const api = (path, body, status) => h.api(path, owner, body, status)
 const apply = async plan => api('level.apply', { review: (await api('level.preview', plan)).id })
 const reader = fx.staff.managerb, alternate = fx.staff.employee, subject = fx.staff.hr
 const as = (who, path, body, status) => h.api(path, who.cookie, body, status)
 const ownerId = (await api('me')).id
 const near = await api('location.create', { name: 'synthetic-willow-9401', timezone: 'UTC' })
 const far = await api('location.create', { name: 'synthetic-willow-9402', timezone: 'UTC' })
 await api('mover.schedule', { period: subject.period, effectiveFrom: day(-3), locationId: near.id, reason: 'synthetic-willow-9403' })
 const keys = ['leave', ...['job', 'compensation'].flatMap(type => ['hr', 'payroll', 'skip_manager'].map(role => `change:${type}:${role}`))]
 const plan = { kind: 'level', name: 'synthetic-willow-9404', permissions: [], scope: { kind: 'group', dimensions: { location: [near.id] } }, approvals: keys }
 const level = await apply(plan)
 const other = await apply({ ...plan, name: 'synthetic-willow-9405' })
 const assign = (who, levels) => apply({ kind: 'assignment', member: who.member, levels })
 const account = await fx.account(subject.period)
 const request = await api('leave.request', { account, startDate: day(40), endDate: day(40), reason: 'synthetic-willow-9406' })
 await as(reader, `leave/${request.id}`, undefined, 404)
 const selectedPreview=await api('level.preview',{kind:'assignment',member:reader.member,levels:[level.id]})
 assert.ok(selectedPreview.impact[0].addedApprovals.includes('leave'))
 const addedPending=selectedPreview.approvalImpact.find(row=>row.source===`leave:${request.id}`)
 assert.ok(addedPending.after.some(row=>row.id===reader.member))
 assert.equal(addedPending.afterOwner,reader.member)
 assert.equal(addedPending.orphaned,false)
 await api('level.apply',{review:selectedPreview.id})
 const detail = await as(reader, `leave/${request.id}`)
 assert.equal(detail.canDecide, true)
 assert.equal(detail.balanceMinutes, undefined)
 assert.deepEqual(detail.ledger, [])
 assert.ok(!('reason' in detail))
 assert.ok((await as(reader, 'approvals')).some(row => row.id === request.id))
 assert.equal((await as(reader, `people/${subject.person}`)).leave, undefined)
 assert.equal((await as(reader, `people/${subject.person}`)).pay, undefined)
 assert.deepEqual((await as(reader, 'me')).permissions, [])
 const work = async key => (await api('work')).items.find(row => row.source === key)
 const source = `leave:${request.id}`
 const initial = await work(source)
 assert.equal(initial.owner, reader.member)
 assert.ok(initial.candidates.every(member => member.id !== ownerId && member.id !== subject.member))
 await assign(alternate, [level.id])
 assert.equal((await work(source)).owner, reader.member, 'A still-eligible owner keeps the work')
 const revokedPreview=await api('level.preview',{kind:'assignment',member:reader.member,levels:[]})
 assert.ok(revokedPreview.impact[0].removedApprovals.includes('leave'))
 const movedPending=revokedPreview.approvalImpact.find(row=>row.source===source)
 assert.equal(movedPending.afterOwner,alternate.member)
 assert.equal(movedPending.reassigned,true)
 const reviewPage=await (await h.raw(`/app/access?levelReview=${revokedPreview.id}`,{cookie:owner})).text()
 assert.ok(reviewPage.includes(`/app/leave/${request.id}`))
 await api('level.apply',{review:revokedPreview.id})
 const reassigned = await work(source)
 assert.equal(reassigned.owner, alternate.member)
 assert.notEqual(reassigned.revision, initial.revision)
 assert.ok(reassigned.history.some(row => row.kind === 'approval.routed'))
 await as(reader, `leave/${request.id}`, undefined, 404)
 await as(reader, 'leave.decide', { request: request.id, decision: 'approve' }, 404)
 const orphanPreview=await api('level.preview',{kind:'assignment',member:alternate.member,levels:[]})
 const orphanPending=orphanPreview.approvalImpact.find(row=>row.source===source)
 assert.equal(orphanPending.afterOwner,null)
 assert.equal(orphanPending.orphaned,true)
 await api('level.apply',{review:orphanPreview.id})
 const orphan = await work(source)
 assert.equal(orphan.owner, null)
 assert.equal(orphan.effectiveOwner, null)
 assert.equal(orphan.orphaned, true)
 assert.deepEqual(orphan.candidates, [])
 await api('work.schedule', { source, revision: orphan.revision, owner: ownerId, dueDate: day(40), nextAction: 'synthetic-willow-9407' }, 403)
 await api('leave.decide', { request: request.id, decision: 'approve' }, 403)
 await as(subject, 'leave.decide', { request: request.id, decision: 'approve' }, 403)
 await assign(reader, [level.id])
 assert.equal((await work(source)).owner, reader.member)
 const approved = await h.submit('leave.decide', reader.cookie, { request: request.id, decision: 'approve' }, `/app/leave/${request.id}`)
 assert.ok(!approved.searchParams.has('error'), approved.href)
 assert.equal((await api(`leave/${request.id}`)).status, 'approved')
 assert.ok((await api(`people/${subject.person}`)).leave.accounts.find(row => row.id === account).ledger.some(row => row.kind === 'use'))
 assert.equal((await as(reader, `leave/${request.id}`)).canCancel, false, 'Decision selection adds no cancellation right')

 const template = await publishTemplate(h, owner, { name: 'synthetic-willow-9408', kind: 'mover', taskTitle: ['synthetic-willow-9409'], taskAssignee: ['hr'], taskDueDays: ['0'] })
 const previousLevels = (await api('levels')).assignments.filter(row => row.member_id === subject.member).map(row => row.level_id)
 await assign(subject, [...previousLevels, level.id])
 await assign(alternate, [other.id])
 let sequence = 0
 for (const type of ['job', 'compensation']) for (const role of ['hr', 'payroll', 'skip_manager']) {
  const configured = await h.submit('change.chain', owner, { requestType: type, template: template.id, stepRole: [role], stepLevel: [level.id] }, '/app/changes')
  assert.ok(!configured.searchParams.has('error'), configured.href)
  const savedName = (await api('levels')).levels.find(row => row.id === level.id).name
  const body = { person: subject.person, effectiveFrom: day(10 + sequence), reason: `synthetic-willow-${9420 + sequence}`, ...(type === 'job' ? { jobTitle: `synthetic-willow-${9430 + sequence}` } : { payBasis: 'salary', payAmount: (84567.19 + sequence).toFixed(2) }) }
  const proposed = await api('change.request', body)
  const selected = await as(reader, `change-requests/${proposed.id}`)
  assert.equal(selected.steps[0].role, role)
  assert.equal(selected.steps[0].level, level.id)
  assert.equal(selected.steps[0].approvalKey, `change:${type}:${role}`)
  assert.ok(selected.steps[0].label.includes(savedName))
  assert.equal(selected.mayDecide, true)
  assert.ok(selected.changes.every(change => change.to === 'Withheld' || change.to.startsWith('Withheld')))
  assert.equal((await api(`change-requests/${proposed.id}`)).mayDecide, false, 'The requester never decides')
  assert.equal((await as(subject, `change-requests/${proposed.id}`)).mayDecide, false, 'The subject never decides')
  await as(alternate, `change-requests/${proposed.id}`, undefined, 404)
  const page = await (await h.raw(`/app/changes/${proposed.id}`, { cookie: reader.cookie })).text()
  assert.ok(page.includes('/app/do/change.decide'))
  assert.ok(!page.includes('81234.56') && !page.includes('PRIVATE-hr'))
  if (sequence === 0) {
   await apply({ ...plan, level: level.id, name: 'synthetic-willow-9410' })
   assert.equal((await as(reader, `change-requests/${proposed.id}`)).steps[0].label, selected.steps[0].label, 'A revision retains its reviewed role label')
  }
  const pending = await work(`change-request:${proposed.id}`)
  assert.ok(pending.candidates.some(member => member.id === reader.member))
  assert.ok(pending.candidates.every(member => member.id !== ownerId && member.id !== subject.member && member.id !== alternate.member))
  const decision = await h.submit('change.decide', reader.cookie, { request: proposed.id, state: selected.state, decision: 'approve' }, `/app/changes/${proposed.id}`)
  assert.ok(!decision.searchParams.has('error'), decision.href)
  const executed = await api(`change-requests/${proposed.id}`)
  assert.equal(executed.status, 'approved')
  assert.ok(executed.result.terms)
  assert.deepEqual((await as(reader, 'me')).permissions, [])
  sequence++
 }

 // A bound selection is additive to existing native HR, while its scope remains current.
 const outside = await fx.join('synthetic-willow-9440', { locationId: far.id })
 await api('change.chain', { requestType: 'job', template: template.id, stepRole: ['hr'], stepLevel: [level.id] })
 const outsideRequest = await api('change.request', { person: outside.person, effectiveFrom: day(20), jobTitle: 'synthetic-willow-9441', reason: 'synthetic-willow-9442' })
 await as(reader, `change-requests/${outsideRequest.id}`, undefined, 404)
 const native = await as(subject, `change-requests/${outsideRequest.id}`)
 assert.equal(native.mayDecide, true)
 await as(subject, 'change.decide', { request: outsideRequest.id, state: native.state, decision: 'decline' })
 const live = await api('change.request', { person: subject.person, effectiveFrom: day(21), jobTitle: 'synthetic-willow-9443', reason: 'synthetic-willow-9444' })
 await api('mover.schedule', { period: subject.period, effectiveFrom: day(-1), locationId: far.id, reason: 'synthetic-willow-9445' })
 await as(reader, `change-requests/${live.id}`, undefined, 404)
 assert.ok(!(await as(reader, 'work')).items.some(row => row.source === `change-request:${live.id}`))
 console.log('ROLE-011 routing: PASS — selected leave and six bound change roles, exact proposal admission without private rights, requester/subject refusal, current scoped membership, native decisions and eligible work reassignment/orphans')
}
