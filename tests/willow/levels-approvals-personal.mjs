// ROLE-011: selecting a decision never supplies the field, bytes or ordinary write right.
import assert from 'node:assert/strict'
import { day, today } from './regression-fixture.mjs'
import { file } from './harness.mjs'

export async function personalApprovalProof(h, owner, fx) {
 const { api, staff: s } = fx
 const reviewer=s.managerb, subject=s.employee
 const as=(who,path,body,status)=>h.api(path,who.cookie,body,status)
 const apply=async plan=>api('level.apply',{review:(await api('level.preview',plan)).id})
 const location=await api('location.create',{name:'synthetic-willow-1101',timezone:'UTC'})
 const outsideLocation=await api('location.create',{name:'synthetic-willow-1102',timezone:'UTC'})
 await api('mover.schedule',{period:subject.period,effectiveFrom:day(-3),locationId:location.id,reason:'synthetic-willow-1103'})
 const scope={kind:'group',dimensions:{location:[location.id]}}
 const category=await api('category.create',{name:'synthetic-willow-1104'})
 const otherCategory=await api('category.create',{name:'synthetic-willow-1105'})
 const definition={key:'synthetic_willow_1106',classification:'hr',label:'synthetic-willow-1106',type:'text',required:false,effectiveFrom:day(-20),employeeRead:false,managerRead:false,retired:false,validation:{maxLength:160}}
 const field=await api('customField.define',{definition})
 const otherField=await api('customField.define',{definition:{...definition,key:'synthetic_willow_1107',label:'synthetic-willow-1107'}})
 await api('customField.write',{person:subject.person,effectiveFrom:day(-10),values:{[field.id]:'synthetic-willow-1108',[otherField.id]:'synthetic-willow-1109'}})
 const subjectLevel=await apply({kind:'level',name:'synthetic-willow-1110',permissions:[],selfFields:{phone:'approval',address:'approval'},documentCategories:{self:{[category.id]:'approval',[otherCategory.id]:'approval'},others:{}}})
 await apply({kind:'assignment',member:subject.member,levels:[subjectLevel.id]})
 const selected=['self:legalName','self:personal','self:dependent',`document:${category.id}`,`custom:${field.id}`]
 const reviewPlan={kind:'level',name:'synthetic-willow-1111',permissions:[],scope,approvals:selected,otherFields:{phone:'view'},documentCategories:{self:{},others:{[category.id]:'view',[otherCategory.id]:'view'}}}
 const level=await apply(reviewPlan)
 await apply({kind:'assignment',member:reviewer.member,levels:[level.id]})
 const decide=(who,id,decision='approve',status)=>as(who,'self.decide',{change:id,decision,comment:'synthetic-willow-1112'},status)
 const phone=await as(subject,'self.request',{kind:'personal',field:'phone',value:'synthetic-willow-1113'})
 const detail=await as(reviewer,`self-changes/${phone.id}`)
 assert.deepEqual(detail.after,{phone:'synthetic-willow-1113'})
 assert.equal(detail.mayDecide,true)
 assert.deepEqual((await as(reviewer,`people/${subject.person}`)).private,{phone:'PRIVATE-employee'},'Selection adds only the selected proposal, not a private facet')
 await as(reviewer,'person.field',{person:subject.person,revision:(await api(`people/${subject.person}`)).revision,field:'phone',value:'synthetic-willow-1114'},403)
 await decide(reviewer,phone.id)
 assert.equal((await api(`people/${subject.person}`)).private.phone,'synthetic-willow-1113')
 await decide(reviewer,phone.id,'approve',409)
 const address=await as(subject,'self.request',{kind:'personal',field:'address',value:'synthetic-willow-1115'})
 await as(reviewer,`self-changes/${address.id}`,undefined,404)
 assert.ok(!(await as(reviewer,'self-changes')).some(row=>row.id===address.id))
 await decide(reviewer,address.id,'approve',403)
 await decide(s.hr,address.id,'reject')
 const legal=await as(subject,'self.request',{kind:'legalName',legalName:'synthetic-willow-1116'})
 await decide(subject,legal.id,'approve',403)
 await decide(reviewer,legal.id)
 assert.equal((await api(`people/${subject.person}`)).legalName,'synthetic-willow-1116')

 const pending=await as(subject,'document.propose',{person:subject.person,category:category.id,title:'synthetic-willow-1117',file:file('synthetic-willow-1118.txt','synthetic-willow-1118')})
 const unselected=await as(subject,'document.propose',{person:subject.person,category:otherCategory.id,title:'synthetic-willow-1119',file:file('synthetic-willow-1120.txt','synthetic-willow-1120')})
 assert.equal((await h.raw(`/app/files/document/${pending.version}`,{cookie:reviewer.cookie})).status,200)
 await as(reviewer,`self-changes/${unselected.id}`,undefined,404)
 assert.equal((await h.raw(`/app/files/document/${unselected.version}`,{cookie:reviewer.cookie})).status,404)
 await decide(reviewer,unselected.id,'approve',403)
 assert.ok(!(await as(reviewer,`people/${subject.person}`)).documents.some(row=>row.id===pending.document),'Pending bytes never become published person documents')
 await apply({...reviewPlan,level:level.id,documentCategories:{self:{},others:{[otherCategory.id]:'view'}}})
 await decide(reviewer,pending.id,'approve',403)
 assert.equal((await h.raw(`/app/files/document/${pending.version}`,{cookie:reviewer.cookie})).status,404)
 await apply({...reviewPlan,level:level.id})
 await decide(reviewer,pending.id)
 assert.ok((await as(reviewer,`people/${subject.person}`)).documents.some(row=>row.id===pending.document))
 await as(reviewer,'self.reconcile',{change:pending.id,reference:'synthetic-willow-1121'},403)

 const custom=await as(s.hr,'custom.propose',{person:subject.person,field:field.id,effectiveFrom:today,value:'synthetic-willow-1122'})
 await decide(s.hr,custom.id,'approve',403)
 await as(reviewer,`self-changes/${custom.id}`,undefined,404)
 await decide(reviewer,custom.id,'approve',403)
 const privateRead=await apply({kind:'level',name:'synthetic-willow-1123',permissions:['people.private'],scope})
 await apply({kind:'assignment',member:reviewer.member,levels:[level.id,privateRead.id]})
 await as(reviewer,'custom.propose',{person:subject.person,field:field.id,effectiveFrom:today,value:'synthetic-willow-1124'},403)
 await as(reviewer,'customField.write',{person:subject.person,effectiveFrom:today,values:{[field.id]:'synthetic-willow-1124'}},403)
 const customDetail=await as(reviewer,`self-changes/${custom.id}`)
 assert.equal(customDetail.mayDecide,true)
 assert.equal(customDetail.after.value,'synthetic-willow-1122')
 assert.equal((await api(`people/${subject.person}`)).customFields.fields.find(row=>row.id===field.id).value,'synthetic-willow-1108')
 await decide(reviewer,custom.id)
 assert.equal((await api(`people/${subject.person}`)).customFields.fields.find(row=>row.id===field.id).value,'synthetic-willow-1122')
 const customOther=await as(s.hr,'custom.propose',{person:subject.person,field:otherField.id,effectiveFrom:today,value:'synthetic-willow-1125'})
 await as(reviewer,`self-changes/${customOther.id}`,undefined,404)
 await decide(reviewer,customOther.id,'approve',403)
 const stale=await as(s.hr,'custom.propose',{person:subject.person,field:field.id,effectiveFrom:today,value:'synthetic-willow-1126'})
 await api('customField.write',{person:subject.person,effectiveFrom:today,values:{[field.id]:'synthetic-willow-1127'}})
 await decide(reviewer,stale.id,'approve',409)
 assert.equal((await api(`self-changes/${stale.id}`)).status,'pending')
 const dependent=await as(subject,'self.request',{kind:'dependent',values:{name:'synthetic-willow-1128',relationship:'synthetic-willow-1129',date_of_birth:'2015-01-01'}})
 await decide(reviewer,dependent.id)
 assert.ok((await api(`people/${subject.person}`)).recordTables.tables.find(row=>row.key==='dependents').rows.some(row=>row.values.name==='synthetic-willow-1128'))
 const revoked=await as(subject,'self.request',{kind:'personal',field:'phone',value:'synthetic-willow-1130'})
 await apply({...reviewPlan,level:level.id,approvals:selected.filter(key=>key!=='self:personal')})
 await decide(reviewer,revoked.id,'approve',403)
 await apply({...reviewPlan,level:level.id})
 await api('mover.schedule',{period:subject.period,effectiveFrom:day(-2),locationId:outsideLocation.id,reason:'synthetic-willow-1131'})
 await decide(reviewer,revoked.id,'approve',403)
 assert.equal((await api(`people/${subject.person}`)).private.phone,'synthetic-willow-1113')
 assert.deepEqual((await as(reviewer,'me')).permissions,[],'Scoped read plus selected decisions adds no employer-wide authority')
 console.log('ROLE-011 personal approvals: PASS — exact proposal selection, current field/category/custom reads, native decisions, no ordinary edits, no self decisions, source/selection/scope revocation and pending byte fences')
 return {reviewer,subject,level,field,category,custom,pending}
}
