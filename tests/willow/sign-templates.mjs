// Exact shared PDF versions and typed placements become native signature templates, never sends.
import assert from 'node:assert/strict'
import { file } from './harness.mjs'
import { pdf } from './fixtures.mjs'
export async function signatureTemplateProof(h,owner,staff) {
 const api=(path,body,status)=>h.api(path,owner,body,status)
 const hr=(path,body,status)=>h.api(path,staff.hr.cookie,body,status)
 const folder=await hr('company.folder',{name:'synthetic-willow-15100',audience:{kind:'everyone',id:null}})
 const source=await hr('company.file',{folder:folder.id,title:'synthetic-willow-15101',file:file('policy.pdf',pdf('synthetic-willow-15102'))})
 const category=await api('category.create',{name:'synthetic-willow-15103',subjectReads:true})
 const fields=[{signer:0,kind:'signature',page:1,x:0.1,y:0.7,width:0.3,height:0.1},{signer:1,kind:'signature',page:1,x:0.5,y:0.7,width:0.3,height:0.1}]
 const input={title:'synthetic-willow-15104',source:source.versionId,category:category.id,signers:['employee','hr'],fields}
 await h.api('signature.template',staff.employee.cookie,input,403)
 await h.api('signature-templates',staff.managera.cookie,undefined,403)
 await hr('signature.template',{...input,signers:['employee','owner']},400)
 await hr('signature.template',{...input,fields:[{...fields[0],x:0.9},fields[1]]},400)
 await hr('signature.template',{...input,fields:[fields[0]]},400)
 const template=await hr('signature.template',input)
 const row=(await hr('signature-templates')).find(t=>t.id===template.id)
 assert.deepEqual(row.fields,fields)
 assert.deepEqual(row.signers,['employee','hr'])
 assert.equal(row.sourceVersion,source.versionId)
 assert.equal(row.approvedAt,null)
 assert.equal(row.current,true)
 const bytes=await h.raw(row.sourceUrl,{cookie:staff.hr.cookie})
 assert.equal(bytes.status,200)
 assert.equal(await bytes.text(),pdf('synthetic-willow-15102').toString())
 await hr('signature.template.approve',{template:template.id,digest:row.digest,reviewed:false},400)
 await hr('signature.template.approve',{template:template.id,digest:'0'.repeat(64),reviewed:true},409)
 await h.api('signature.template.approve',staff.employee.cookie,{template:template.id,digest:row.digest,reviewed:true},403)
 await hr('signature.template.approve',{template:template.id,digest:row.digest,reviewed:true})
 await hr('signature.template.approve',{template:template.id,digest:row.digest,reviewed:true},409)
 const v2=await hr('signature.template',{...input,template:template.id,title:'synthetic-willow-15105'})
 const revised=(await hr('signature-templates')).find(t=>t.id===v2.id)
 assert.equal(revised.version,2)
 assert.equal(revised.approvedAt,null)
 const old=(await hr('signature-templates')).find(t=>t.id===template.id)
 assert.equal(old.current,false)
 assert.ok(old.approvedAt)
 assert.deepEqual(old.fields,row.fields,'A new draft retains the approved configuration as immutable history')
 await hr('signature.template',{...input,template:template.id},409)
 await hr('company.file',{id:source.id,folder:folder.id,title:'synthetic-willow-15106',file:file('policy.pdf',pdf('synthetic-willow-15107'))})
 await hr('signature.template.approve',{template:v2.id,digest:revised.digest,reviewed:true},409)
 await hr('signature.template',input,409)
 assert.equal((await hr('signature-templates')).find(t=>t.id===v2.id).current,false)
 const before=(await api('levels')).assignments.filter(a=>a.member_id===staff.hr.member).map(a=>a.level_id)
 const review=await api('level.preview',{kind:'assignment',member:staff.hr.member,levels:[]})
 await api('level.apply',{review:review.id})
 await hr('signature-templates',undefined,401)
 staff.hr.cookie=await h.signIn('hr@example.com')
 await hr('signature-templates',undefined,403)
 const restore=await api('level.preview',{kind:'assignment',member:staff.hr.member,levels:before})
 await api('level.apply',{review:restore.id})
 staff.hr.cookie=await h.signIn('hr@example.com')
 const audit=await api('audit')
 assert.ok(audit.some(event=>event.action==='signature.template.approve'&&event.actor===staff.hr.member&&event.subject===template.id))
 assert.ok(!audit.some(event=>event.action==='signature.send'||event.action==='signature.sign'),'Template approval never sends or signs a document')
 return {template:template.id,version:v2.id,digest:row.digest}
}
